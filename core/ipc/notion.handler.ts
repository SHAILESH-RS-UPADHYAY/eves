import { ipcMain } from '../runtime'
import type { Meeting, MeetingAnalysis, IpcResult } from '../../src/types'

const NOTION_MCP_URL = 'https://mcp.notion.com/mcp'

export function registerNotionHandlers() {
  ipcMain.handle('notion:listDatabases', async (_event, args: { apiKey: string }): Promise<IpcResult<{ id: string; title: string }[]>> => {
    try {
      const res = await fetch(`${NOTION_MCP_URL}/databases`, {
        headers: { Authorization: `Bearer ${args.apiKey}` }
      })
      if (!res.ok) return { success: false, error: `Notion MCP returned ${res.status}` }
      const data = await res.json()
      const dbs = (data.databases ?? []).map((db: any) => ({
        id: db.id,
        title: db.title?.[0]?.plain_text ?? 'Untitled'
      }))
      return { success: true, data: dbs }
    } catch (err: any) {
      return { success: false, error: err?.message ?? 'Notion list failed' }
    }
  })

  ipcMain.handle('notion:createPage', async (_event, args: { databaseId: string; meeting: Meeting; analysis: MeetingAnalysis }): Promise<IpcResult<string>> => {
    try {
      const { databaseId, meeting, analysis } = args
      const dateStr = meeting.date.split('T')[0]
      const title = `[${dateStr}] [${analysis.meetingType}] — ${analysis.tldr}`

      const body = {
        parent: { database_id: databaseId },
        properties: {
          title: { title: [{ text: { content: title } }] },
          Date: { date: { start: meeting.date } },
          Tags: { multi_select: analysis.suggestedTags.map((t) => ({ name: t })) },
          Urgency: { select: { name: analysis.urgency } },
          Mood: { select: { name: analysis.overallMood } }
        },
        children: [
          {
            object: 'block',
            type: 'callout',
            callout: { rich_text: [{ type: 'text', text: { content: analysis.tldr } }], icon: { type: 'emoji', emoji: '⚡' } }
          },
          { object: 'block', type: 'heading_2', heading_2: { rich_text: [{ type: 'text', text: { content: 'Summary' } }] } },
          { object: 'block', type: 'paragraph', paragraph: { rich_text: [{ type: 'text', text: { content: analysis.summary } }] } },
          { object: 'block', type: 'heading_2', heading_2: { rich_text: [{ type: 'text', text: { content: 'Action Items' } }] } },
          ...analysis.actionItems.map((item) => ({
            object: 'block',
            type: 'to_do',
            to_do: {
              rich_text: [{ type: 'text', text: { content: `${item.task} — ${item.owner} (${item.priority})` } }],
              checked: item.completed
            }
          })),
          { object: 'block', type: 'heading_2', heading_2: { rich_text: [{ type: 'text', text: { content: 'Key Decisions' } }] } },
          ...analysis.keyDecisions.map((d) => ({
            object: 'block',
            type: 'bulleted_list_item',
            bulleted_list_item: { rich_text: [{ type: 'text', text: { content: `${d.decision} — ${d.madeBy}` } }] }
          })),
          { object: 'block', type: 'heading_2', heading_2: { rich_text: [{ type: 'text', text: { content: 'Speaker Profiles' } }] } },
          ...analysis.speakerProfiles.map((s) => ({
            object: 'block',
            type: 'paragraph',
            paragraph: { rich_text: [{ type: 'text', text: { content: `${s.name}: ${s.communicationStyle}. Agenda: ${s.agenda}` } }] }
          })),
          { object: 'block', type: 'heading_2', heading_2: { rich_text: [{ type: 'text', text: { content: 'Open Questions' } }] } },
          ...analysis.openQuestions.map((q) => ({
            object: 'block',
            type: 'bulleted_list_item',
            bulleted_list_item: { rich_text: [{ type: 'text', text: { content: q } }] }
          })),
          { object: 'block', type: 'divider', divider: {} },
          { object: 'block', type: 'paragraph', paragraph: { rich_text: [{ type: 'text', text: { content: `Generated by EVES • ${new Date().toISOString()}` } }] } }
        ]
      }

      const res = await fetch(`${NOTION_MCP_URL}/pages`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${args}`
        },
        body: JSON.stringify(body)
      })

      if (!res.ok) return { success: false, error: `Notion createPage returned ${res.status}` }
      const data = await res.json()
      return { success: true, data: data.url ?? '' }
    } catch (err: any) {
      return { success: false, error: err?.message ?? 'Notion export failed' }
    }
  })
}
